/**
 * Banco de items de la Academia (ROOMBIR-ACADEMY-SPEC.md §6 y Anexo A).
 *
 * Vive en el API y NO en el front: el cliente nunca recibe `correct` ni `why`
 * de un item antes de responderlo. Las opciones se escriben con la correcta en
 * cualquier lugar (aca casi siempre la primera): el servicio las permuta por
 * intento.
 *
 * Reglas de redaccion (Haladyna, Downing y Rodriguez 2002; Rodriguez 2005):
 * tres opciones, una correcta, distractores sacados de errores reales, nada de
 * "todas las anteriores", negaciones solo resaltadas, largos parecidos. Las
 * tres opciones de un item tienen que ser DISTINTAS: la practica identifica la
 * elegida por su texto.
 *
 * `critical`: lo que no se puede confundir nunca. Los conceptos base del
 * negocio (vender por categoria o por unidad), las afirmaciones prohibidas, lo
 * que Roombir NO hace hoy, paridad y pagos. Se aprueba con 100% de esos.
 *
 * Examenes (spec §3): 1 = bloques 0, A y B (el mundo del alojamiento y que se
 * vende); 2 = C y D (como llega una reserva y la tecnologia); 3 = E y F
 * (Roombir y tu rol). Roombir aparece recien en el examen 3, a proposito.
 *
 * `sources`: ids del dosier (`dosier:3.1`), secciones de FULL-SYSTEM o del
 * Manual. `verifiedAt` = ultima verificacion.
 */

